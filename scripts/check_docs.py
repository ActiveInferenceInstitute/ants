#!/usr/bin/env python3
"""Documentation checks: relative links, and the generated gate-metrics page.

``uv run python scripts/check_docs.py`` (the ``docs`` arm of
``scripts/gate.py``) verifies that every relative link in tracked Markdown
resolves and that ``docs/_generated/gate-metrics.md`` still matches the render
of ``docs/_generated/gate-metrics.json``.

``--write-metrics`` folds the receipts written by ``scripts/gate.py`` into the
``latest`` member of that JSON file and regenerates the Markdown page; the
generated numbers are never hand-edited.

Exit codes: 0 pass, 1 link or metrics failure.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
import urllib.parse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RECEIPTS = REPO_ROOT / ".gate-cache" / "latest.json"
METRICS_JSON = REPO_ROOT / "docs" / "_generated" / "gate-metrics.json"
METRICS_MD = REPO_ROOT / "docs" / "_generated" / "gate-metrics.md"
ARM_ORDER = ("lint", "test-fast", "test", "docs", "gnn")

LINK = re.compile(r"!?\[[^\]]*\]\(([^)]+)\)")
SCHEME = re.compile(r"^[a-z][a-z0-9+.-]*:", re.IGNORECASE)


def tracked_markdown() -> list[Path]:
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", "*.md"],
        cwd=REPO_ROOT,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        check=True,
    )
    return [REPO_ROOT / name for name in result.stdout.split("\0") if name]


def _unfenced_lines(text: str):
    fenced = False
    for number, line in enumerate(text.splitlines(), start=1):
        stripped = line.lstrip()
        if stripped.startswith(("```", "~~~")):
            fenced = not fenced
            continue
        if not fenced:
            yield number, line


def broken_links() -> list[str]:
    broken: list[str] = []
    for document in tracked_markdown():
        text = document.read_text(encoding="utf-8")
        for number, line in _unfenced_lines(text):
            for match in LINK.finditer(line):
                raw = match.group(1).strip()
                if raw.startswith("<") and raw.endswith(">"):
                    raw = raw[1:-1]
                target = raw.split()[0] if raw.split() else ""
                if not target or target.startswith("#") or SCHEME.match(target):
                    continue
                path_part = urllib.parse.unquote(target.split("#", 1)[0].split("?", 1)[0])
                if not path_part:
                    continue
                resolved = (document.parent / path_part).resolve()
                if not resolved.exists():
                    relative = document.relative_to(REPO_ROOT)
                    broken.append(f"{relative}:{number}: {target}")
    return broken


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def _arm_rows(section: dict) -> list[str]:
    order = list(ARM_ORDER) + sorted(set(section.get("arms", {})) - set(ARM_ORDER))
    rows = ["| Arm | Command | Wall time (s) | Facts |", "| --- | --- | ---: | --- |"]
    for name in order:
        entry = section.get("arms", {}).get(name)
        if entry is None:
            continue
        commands = "<br>".join(f"`{_cell(command)}`" for command in entry.get("commands", [])) or "—"
        seconds = entry.get("seconds")
        timing = f"{seconds:.2f}" if isinstance(seconds, (int, float)) else "—"
        facts = ", ".join(
            f"{key}={_cell(str(value))}" for key, value in sorted(entry.get("facts", {}).items())
        )
        rows.append(f"| `{name}` | {commands} | {timing} | {facts or '—'} |")
    return rows


def render(data: dict) -> str:
    lines = [
        "# Gate metrics",
        "",
        "<!-- generated by scripts/check_docs.py --write-metrics; do not edit -->",
        "",
        "Wall time per gate arm, measured one run each on this host. The numbers",
        "are a record of one measurement, not a benchmark: treat them as an order",
        "of magnitude and re-run `uv run python scripts/gate.py all` before citing",
        "a change. Machine-readable source: [`gate-metrics.json`](gate-metrics.json).",
        "",
        "Refresh with `uv run python scripts/gate.py metrics`; the `docs` arm fails",
        "when this page and the JSON diverge.",
        "",
    ]
    for key, title in (("baseline", "Baseline"), ("latest", "Latest")):
        section = data.get(key)
        if not section:
            continue
        lines += [
            f"## {title} — {section.get('label', key)}",
            "",
            (
                f"Measured: {section.get('measured_at', 'unknown')} · "
                f"host: {section.get('platform', 'unknown')} · "
                f"Python: {section.get('python', 'unknown')}"
            ),
            "",
            *_arm_rows(section),
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def write_metrics() -> int:
    if not RECEIPTS.is_file():
        print(f"no receipts at {RECEIPTS.relative_to(REPO_ROOT)}; run arms first", file=sys.stderr)
        return 1
    receipts = json.loads(RECEIPTS.read_text(encoding="utf-8"))
    data = {"schema": "ants-gate-metrics/v1"}
    if METRICS_JSON.is_file():
        data = json.loads(METRICS_JSON.read_text(encoding="utf-8"))
    entries = [entry for entry in receipts.get("arms", {}).values()]
    if not entries:
        print("the receipt file has no arms; run arms first", file=sys.stderr)
        return 1
    ordered = sorted(entries, key=lambda entry: entry.get("measured_at", ""))
    data["latest"] = {
        "label": "scripts/gate.py on this host",
        "measured_at": ordered[-1].get("measured_at", "unknown"),
        "platform": ordered[-1].get("platform", "unknown"),
        "python": ordered[-1].get("python", "unknown"),
        "arms": {
            name: receipts["arms"][name]
            for name in ARM_ORDER
            if name in receipts.get("arms", {})
        },
    }
    METRICS_JSON.parent.mkdir(parents=True, exist_ok=True)
    handle, temp = tempfile.mkstemp(
        dir=METRICS_JSON.parent, prefix=".gate-metrics.", suffix=".json", text=True
    )
    with open(handle, "w", encoding="utf-8") as stream:
        json.dump(data, stream, indent=2, sort_keys=True)
        stream.write("\n")
    Path(temp).replace(METRICS_JSON)
    METRICS_MD.write_text(render(data), encoding="utf-8")
    print(
        f"wrote {METRICS_JSON.relative_to(REPO_ROOT)} and {METRICS_MD.relative_to(REPO_ROOT)}"
    )
    return 0


def check_metrics() -> list[str]:
    if not METRICS_JSON.is_file():
        return [f"{METRICS_JSON.relative_to(REPO_ROOT)} is missing"]
    try:
        data = json.loads(METRICS_JSON.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [f"{METRICS_JSON.relative_to(REPO_ROOT)} is unreadable: {exc}"]
    expected = render(data)
    actual = METRICS_MD.read_text(encoding="utf-8") if METRICS_MD.is_file() else ""
    if actual != expected:
        return [
            (
                f"{METRICS_MD.relative_to(REPO_ROOT)} does not match the render of "
                f"{METRICS_JSON.relative_to(REPO_ROOT)}; run "
                "`uv run python scripts/gate.py metrics`"
            )
        ]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write-metrics", action="store_true", help="regenerate the metrics page")
    args = parser.parse_args(argv)

    if args.write_metrics:
        return write_metrics()

    problems = [f"broken relative link: {item}" for item in broken_links()]
    problems += check_metrics()
    for problem in problems:
        print(f"FAIL: {problem}", file=sys.stderr)
    if problems:
        return 1
    print(f"docs: {len(tracked_markdown())} Markdown files, relative links and metrics consistent")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
